/**
 * 日本語のまま画像モデルへ渡そうとしている（D-033）。**編集のときだけ止める。**
 *
 * 実測で差が出た（同じ Mac・同じ seed）:
 *   - 生成（z-image-turbo）は日本語のプロンプトでも主題どおりの絵を描いた。
 *     多言語で学習された生成モデルなので、止めると使える経路を潰すことになる
 *   - 編集（FLUX.2 Klein）は日本語を汲まず、指示が届かないまま親画像がほぼそのまま返る。
 *     45 秒かけて必ず何も変わらないので、**走らせる前に止めるほうが親切**である
 *
 * `code` を持たせるのは、画面が文言ではなく印で次の手を出せるようにするため。
 */
export class PromptNotTranslatedError extends Error {
  readonly code = 'prompt-not-translated' as const

  constructor() {
    super(
      '指示を英語へ書き直せなかったので、編集を走らせませんでした。' +
        '編集モデルは日本語をほとんど汲めないため、このまま走らせても絵は変わりません。' +
        '設定の「AI」で解釈に使うモデルを見直すか、指示を英語で書いてください。' +
        'すでにある版なら「清書を直して出し直す」から自分で英語の清書を書けます。',
    )
    this.name = 'PromptNotTranslatedError'
  }
}
